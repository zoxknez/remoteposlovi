function defaultNote(support: RegionSupport, country: CountryCode): string {
  if (support === "confirmed" && isLocal(country)) {
    return `Lokalni servis za tržište: ${getCountry(country).name}.`;
  }
  switch (support) {
    case "confirmed":
      return "Dostupno iz regiona - servis eksplicitno podržava korisnike sa Balkana.";
    case "partial":
      return "Zavisi od oglasa - platforma je međunarodna, a svaki oglas ili projekat ima sopstvena geografska ograničenja.";
    case "not-supported":
      return "Region nije podržan prema javno dostupnim uslovima platforme.";
    default:
      return "Dostupnost za Balkan nije jasno navedena. Proverite uslove pre registracije.";
  }
}

function isLocal(country: CountryCode): boolean {
  return country !== "eu" && country !== "global";
}

