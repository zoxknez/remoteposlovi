function defaultNote(support: SerbiaSupport): string {
  switch (support) {
    case "confirmed":
      return "Srbija potvrđena - izvor ima oglase ili filter koji eksplicitno uključuje Srbiju.";
    case "partial":
      return "Zavisi od oglasa - platforma ima međunarodne oglase, ali svaki oglas ima sopstvena geografska ograničenja.";
    case "not-supported":
      return "Srbija nije podržana prema javno dostupnim uslovima platforme.";
    default:
      return "Lokacija nije jasno navedena na nivou platforme. Proverite konkretan oglas.";
  }
}

